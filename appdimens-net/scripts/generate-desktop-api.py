#!/usr/bin/env python3
# Regenerates the DimenFunction enum and XAML markup extensions of the WPF / WinUI 3 /
# Windows Forms adapters (AppDimens.Net.Wpf, .WinUI, .WinForms).
# Usage: python3 scripts/generate-desktop-api.py
import os, sys

root = sys.argv[1] if len(sys.argv) > 1 else os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
H = "// Generated by scripts/generate-desktop-api.py — edit the script, not this file.\n"

scaled = [("Sdp","v.Sdp()","smallest-width scaled dp"),("Sdpa","v.Sdpa()","Sdp with aspect-ratio curve"),
          ("Sdpi","v.Sdpi()","Sdp ignoring multi-window"),("Sdpia","v.Sdpia()","Sdpa ignoring multi-window"),
          ("Hdp","v.Hdp()","height-axis dp"),("Hdpa","v.Hdpa()","Hdp with aspect-ratio curve"),("Hdpi","v.Hdpi()","Hdp ignoring multi-window"),
          ("Wdp","v.Wdp()","width-axis dp"),("Wdpa","v.Wdpa()","Wdp with aspect-ratio curve"),("Wdpi","v.Wdpi()","Wdp ignoring multi-window"),
          ("Ssp","v.Ssp()","scalable text size (sp)"),("Sspa","v.Sspa()","Ssp with aspect-ratio curve"),
          ("Sem","v.Sem()","text size ignoring the user font scale"),("Hem","v.Hem()","height-axis text ignoring font scale"),
          ("Wem","v.Wem()","width-axis text ignoring font scale")]
fluid = [(f"F{a}{s}", f"v.F{a}{s}()", f"fluid strategy ({a}{' + aspect ratio' if 'a' in s else ''}{' ignoring multi-window' if 'i' in s else ''})")
         for a in ("Sdp","Hdp","Wdp") for s in ("","a","i","ia")]
percent = [(f"P{a}{s}", f"v.P{a}{s}()", f"percent strategy ({a}{' + aspect ratio' if 'a' in s else ''}{' ignoring multi-window' if 'i' in s else ''})")
           for a in ("Sdp","Hdp","Wdp") for s in ("","a","i","ia")]
space = [("SpaceW","v.SpaceWDp(AppDimensAmbient.Require())","literal percent of the window width (Value = %)"),
         ("SpaceH","v.SpaceHDp(AppDimensAmbient.Require())","literal percent of the window height (Value = %)")]
allf = scaled + fluid + percent + space

def enum_file(ns):
    s = H + f"""using AppDimens.Net.Code.Fluid;
using AppDimens.Net.Code.Percent;
using AppDimens.Net.Code.Scaled;

namespace {ns};

/// <summary>AppDimens functions usable from XAML / converters (scaled, fluid and percent strategies).</summary>
public enum DimenFunction
{{
"""
    for n,_,d in allf: s += f"    /// <summary>{d}.</summary>\n    {n},\n"
    s += """}

/// <summary>Evaluates a <see cref="DimenFunction"/> against the ambient window context.</summary>
public static class DimenFunctionExtensions
{
    /// <summary>Returns the scaled value in device-independent units (dp / DIP).</summary>
    public static double Evaluate(this DimenFunction function, int v) => function switch
    {
"""
    for n,e,_ in allf: s += f"        DimenFunction.{n} => {e},\n"
    s += """        _ => throw new ArgumentOutOfRangeException(nameof(function), function, null),
    };
}
"""
    return s

def ext_file(ns, wpf):
    s = H + ("using System.Windows.Markup;\n\n" if wpf else "") + f"namespace {ns};\n"
    for n,_,d in allf:
        if wpf:
            s += f"""
/// <summary><c>{{ad:{n} 16}}</c> — {d}.</summary>
[MarkupExtensionReturnType(typeof(object))]
public sealed class {n}Extension : DimenExtensionBase
{{
    public {n}Extension() {{ }}
    public {n}Extension(int value) {{ Value = value; }}
    protected override DimenFunction Function => DimenFunction.{n};
}}
"""
        else:
            s += f"""
/// <summary><c>{{ad:{n} Value=16}}</c> — {d}.</summary>
public sealed class {n}Extension : DimenExtensionBase
{{
    protected override DimenFunction Function => DimenFunction.{n};
}}
"""
    return s

for proj, wpf, ext in [("AppDimens.Net.Wpf", True, True), ("AppDimens.Net.WinUI", False, True), ("AppDimens.Net.WinForms", False, False)]:
    d = os.path.join(root, "src", proj)
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, "DimenFunction.g.cs"), "w").write(enum_file(proj))
    if ext:
        open(os.path.join(d, "DimenExtensions.g.cs"), "w").write(ext_file(proj, wpf))
print(f"generated {len(allf)} functions")
