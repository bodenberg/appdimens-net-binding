// ApiDocGen — writes a Markdown API reference (every public type and member, with the XML doc
// summaries) for the assemblies of one NuGet package. Assemblies are inspected with
// MetadataLoadContext, so Windows-only (WPF / WinForms / WinUI) and MAUI assemblies can be
// documented on any OS without loading them.
//
// Usage:
//   ApiDocGen --title <Package> --out <file.md> --asm <a.dll> [--asm <b.dll> ...]
//             --search <dir> [--search <dir> ...] [--intro <text>]
using System.Reflection;
using System.Runtime.InteropServices;
using System.Text;
using System.Xml.Linq;

var asms = new List<string>();
var search = new List<string>();
string? title = null, outFile = null, intro = null;
for (var i = 0; i < args.Length; i++)
{
    switch (args[i])
    {
        case "--asm": asms.Add(args[++i]); break;
        case "--search": search.Add(args[++i]); break;
        case "--title": title = args[++i]; break;
        case "--out": outFile = args[++i]; break;
        case "--intro": intro = args[++i]; break;
        default: throw new ArgumentException($"Unknown argument {args[i]}");
    }
}
if (title is null || outFile is null || asms.Count == 0)
{
    Console.Error.WriteLine("Usage: ApiDocGen --title T --out F --asm A [--asm B] --search DIR ...");
    return 2;
}

// Resolver: the documented assemblies + every dll under the search dirs (first one per name wins,
// so pass the most specific directories first) + the running core library.
var byName = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
void Add(string path)
{
    var name = Path.GetFileNameWithoutExtension(path);
    byName.TryAdd(name, path);
}
foreach (var a in asms) Add(Path.GetFullPath(a));
foreach (var d in search.Where(Directory.Exists))
    foreach (var f in Directory.EnumerateFiles(d, "*.dll", SearchOption.AllDirectories))
        Add(f);
foreach (var f in Directory.EnumerateFiles(RuntimeEnvironment.GetRuntimeDirectory(), "*.dll"))
    Add(f);

using var mlc = new MetadataLoadContext(new PathAssemblyResolver(byName.Values), "System.Private.CoreLib");

var sb = new StringBuilder();
sb.AppendLine($"# {title} — API reference");
sb.AppendLine();
sb.AppendLine("> Generated by `tools/ApiDocGen` from the compiled assemblies and their XML documentation.");
sb.AppendLine("> Regenerate with `./scripts/generate-docs.sh`. Do not edit by hand.");
sb.AppendLine();
if (intro != null) { sb.AppendLine(intro); sb.AppendLine(); }

var allTypes = new List<(Assembly Asm, Type Type, Dictionary<string, string> Docs)>();
foreach (var path in asms)
{
    var asm = mlc.LoadFromAssemblyPath(Path.GetFullPath(path));
    var docs = LoadDocs(Path.ChangeExtension(path, ".xml"));
    Type[] types;
    try { types = asm.GetExportedTypes(); }
    catch (ReflectionTypeLoadException ex) { types = ex.Types.Where(t => t is not null).ToArray()!; }
    foreach (var t in types) allTypes.Add((asm, t, docs));
}

sb.AppendLine("## Assemblies");
sb.AppendLine();
sb.AppendLine("| Assembly | Public types |");
sb.AppendLine("|----------|-------------:|");
foreach (var g in allTypes.GroupBy(t => t.Asm.GetName().Name))
    sb.AppendLine($"| `{g.Key}` | {g.Count()} |");
sb.AppendLine();

foreach (var ns in allTypes.GroupBy(t => t.Type.Namespace ?? "(global)").OrderBy(g => g.Key))
{
    sb.AppendLine($"## Namespace `{ns.Key}`");
    sb.AppendLine();
    foreach (var (_, type, docs) in ns.OrderBy(t => t.Type.Name))
        WriteType(sb, type, docs);
}

Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outFile))!);
File.WriteAllText(outFile, sb.ToString().Replace("\r\n", "\n"));
Console.WriteLine($"{outFile}: {allTypes.Count} types");
return 0;

static Dictionary<string, string> LoadDocs(string xmlPath)
{
    var map = new Dictionary<string, string>();
    if (!File.Exists(xmlPath)) return map;
    foreach (var m in XDocument.Load(xmlPath).Descendants("member"))
    {
        var id = (string?)m.Attribute("name");
        var summary = m.Element("summary");
        if (id is null || summary is null) continue;
        map[id] = Clean(summary);
    }
    return map;
}

static string Clean(XElement e)
{
    var text = new StringBuilder();
    foreach (var node in e.Nodes())
    {
        switch (node)
        {
            case XText t: text.Append(t.Value); break;
            case XElement x when x.Name == "see" || x.Name == "seealso":
                var cref = (string?)x.Attribute("cref") ?? (string?)x.Attribute("langword") ?? (string?)x.Attribute("href") ?? "";
                var shortName = cref.Contains(':') ? cref[(cref.IndexOf(':') + 1)..] : cref;
                if (shortName.Contains('(')) shortName = shortName[..shortName.IndexOf('(')];
                shortName = shortName.Split('.').Last();
                text.Append('`').Append(x.Value.Length > 0 ? x.Value : shortName).Append('`');
                break;
            case XElement x when x.Name == "paramref" || x.Name == "typeparamref":
                text.Append('`').Append((string?)x.Attribute("name")).Append('`');
                break;
            case XElement x when x.Name == "c" || x.Name == "code":
                text.Append('`').Append(x.Value.Trim()).Append('`');
                break;
            case XElement x:
                text.Append(Clean(x));
                break;
        }
    }
    return string.Join(' ', text.ToString().Split((char[])['\n', '\r', '\t', ' '], StringSplitOptions.RemoveEmptyEntries))
        .Replace("|", "\\|");
}

static void WriteType(StringBuilder sb, Type type, Dictionary<string, string> docs)
{
    var kind = type.IsEnum ? "enum"
        : type.IsInterface ? "interface"
        : type.IsValueType ? (IsRecord(type) ? "record struct" : "struct")
        : type.IsAbstract && type.IsSealed ? "static class"
        : IsRecord(type) ? "record"
        : type.IsAbstract ? "abstract class"
        : type.IsSealed ? "sealed class" : "class";
    sb.AppendLine($"### `{TypeName(type)}` ({kind})");
    sb.AppendLine();
    if (docs.TryGetValue("T:" + DocTypeName(type), out var s)) { sb.AppendLine(s); sb.AppendLine(); }
    var bases = new List<string>();
    if (type.BaseType is { } bt && !type.IsValueType && !type.IsEnum && bt.FullName != "System.Object")
        bases.Add(TypeName(bt));
    bases.AddRange(SafeInterfaces(type).Select(TypeName));
    if (bases.Count > 0) { sb.AppendLine($"Inherits / implements: {string.Join(", ", bases.Select(b => $"`{b}`"))}"); sb.AppendLine(); }

    if (type.IsEnum)
    {
        sb.AppendLine("| Value | Description |");
        sb.AppendLine("|-------|-------------|");
        foreach (var f in type.GetFields(BindingFlags.Public | BindingFlags.Static))
        {
            docs.TryGetValue($"F:{DocTypeName(type)}.{f.Name}", out var d);
            sb.AppendLine($"| `{f.Name}` = {f.GetRawConstantValue()} | {d} |");
        }
        sb.AppendLine();
        return;
    }

    const BindingFlags Flags = BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;
    var rows = new List<(string Group, string Sig, string Doc)>();
    foreach (var c in type.GetConstructors(BindingFlags.Public | BindingFlags.Instance))
        rows.Add(("Constructors", $"{TypeName(type).Split('<')[0]}({Params(c)})", Doc(docs, "M:" + DocTypeName(type) + ".#ctor" + DocParams(c))));
    foreach (var p in type.GetProperties(Flags))
    {
        var get = p.GetMethod is { IsPublic: true };
        var set = p.SetMethod is { IsPublic: true };
        if (!get && !set) continue;
        var isStatic = (p.GetMethod ?? p.SetMethod)!.IsStatic;
        var idx = p.GetIndexParameters();
        var name = idx.Length > 0 ? $"this[{string.Join(", ", idx.Select(x => $"{TypeName(x.ParameterType)} {x.Name}"))}]" : p.Name;
        rows.Add(("Properties", $"{(isStatic ? "static " : "")}{TypeName(p.PropertyType)} {name} {{ {(get ? "get; " : "")}{(set ? "set; " : "")}}}", Doc(docs, $"P:{DocTypeName(type)}.{p.Name}")));
    }
    foreach (var f in type.GetFields(Flags))
        rows.Add(("Fields", $"{(f.IsLiteral ? "const " : f.IsStatic ? "static " : "")}{(f.IsInitOnly ? "readonly " : "")}{TypeName(f.FieldType)} {f.Name}", Doc(docs, $"F:{DocTypeName(type)}.{f.Name}")));
    foreach (var e in type.GetEvents(Flags))
        rows.Add(("Events", $"{(e.AddMethod!.IsStatic ? "static " : "")}event {TypeName(e.EventHandlerType!)} {e.Name}", Doc(docs, $"E:{DocTypeName(type)}.{e.Name}")));
    foreach (var m in type.GetMethods(Flags).Where(m => !m.IsSpecialName && !IsCompilerNoise(m)))
    {
        var gen = m.IsGenericMethodDefinition ? $"<{string.Join(", ", m.GetGenericArguments().Select(a => a.Name))}>" : "";
        var ext = IsExtension(m);
        var modifiers = m.IsStatic && !ext ? "static " : m.IsAbstract && !type.IsInterface ? "abstract " : "";
        rows.Add((ext ? "Extension methods" : "Methods",
            $"{modifiers}{TypeName(m.ReturnType)} {m.Name}{gen}({Params(m, ext)})",
            Doc(docs, $"M:{DocTypeName(type)}.{m.Name}{(m.IsGenericMethodDefinition ? "``" + m.GetGenericArguments().Length : "")}{DocParams(m)}")));
    }

    foreach (var group in rows.GroupBy(r => r.Group))
    {
        sb.AppendLine($"**{group.Key}**");
        sb.AppendLine();
        sb.AppendLine("| Signature | Description |");
        sb.AppendLine("|-----------|-------------|");
        foreach (var r in group.OrderBy(r => r.Sig, StringComparer.Ordinal))
            sb.AppendLine($"| `{r.Sig.Replace("|", "\\|")}` | {r.Doc} |");
        sb.AppendLine();
    }
}

static IEnumerable<Type> SafeInterfaces(Type t)
{
    try { return t.GetInterfaces().Where(i => i.IsPublic && t.BaseType?.GetInterfaces().Contains(i) != true); }
    catch { return []; }
}

static bool IsRecord(Type t)
{
    try { return t.GetMethods().Any(m => m.Name == "<Clone>$") || (t.IsValueType && t.GetMethod("PrintMembers", BindingFlags.NonPublic | BindingFlags.Instance) != null); }
    catch { return false; }
}

static bool IsCompilerNoise(MethodInfo m) =>
    m.Name.Contains('<') || (m.Name is "Equals" or "GetHashCode" or "ToString" or "Deconstruct" or "PrintMembers" && m.DeclaringType != null && IsRecord(m.DeclaringType));

static bool IsExtension(MethodInfo m) =>
    m.IsStatic && m.CustomAttributes.Any(a => a.AttributeType.FullName == "System.Runtime.CompilerServices.ExtensionAttribute");

static string Doc(Dictionary<string, string> docs, string id) => docs.TryGetValue(id, out var d) ? d : "";

static string Params(MethodBase m, bool ext = false) =>
    string.Join(", ", m.GetParameters().Select((p, i) =>
    {
        var prefix = ext && i == 0 ? "this " : "";
        var type = p.ParameterType;
        var mod = "";
        if (type.IsByRef) { mod = p.IsOut ? "out " : p.IsIn ? "in " : "ref "; type = type.GetElementType()!; }
        if (p.CustomAttributes.Any(a => a.AttributeType.Name == "ParamArrayAttribute")) mod = "params ";
        var def = p.HasDefaultValue ? " = " + Literal(p.RawDefaultValue, type) : "";
        return $"{prefix}{mod}{TypeName(type)} {p.Name}{def}";
    }));

static string Literal(object? v, Type t) => v switch
{
    null => t.IsValueType && !IsNullable(t) ? "default" : "null",
    string s => $"\"{s}\"",
    bool b => b ? "true" : "false",
    float f => f.ToString(System.Globalization.CultureInfo.InvariantCulture) + "f",
    double d => d.ToString(System.Globalization.CultureInfo.InvariantCulture),
    _ when t.IsEnum => $"{t.Name}.{EnumName(t, v)}",
    _ => Convert.ToString(v, System.Globalization.CultureInfo.InvariantCulture) ?? "",
};

// Runtime helpers like Nullable.GetUnderlyingType do not recognise MetadataLoadContext types.
static bool IsNullable(Type t) =>
    t.IsGenericType && t.GetGenericTypeDefinition().FullName == "System.Nullable`1";

static string EnumName(Type t, object v)
{
    foreach (var f in t.GetFields(BindingFlags.Public | BindingFlags.Static))
        if (Equals(Convert.ToInt64(f.GetRawConstantValue()), Convert.ToInt64(v))) return f.Name;
    return v.ToString()!;
}

static string TypeName(Type t)
{
    if (t.IsByRef) return TypeName(t.GetElementType()!);
    if (t.IsArray) return TypeName(t.GetElementType()!) + "[]";
    if (t.IsGenericParameter) return t.Name;
    if (IsNullable(t)) return TypeName(t.GetGenericArguments()[0]) + "?";
    var alias = t.FullName switch
    {
        "System.Void" => "void", "System.Int32" => "int", "System.Int64" => "long", "System.Single" => "float",
        "System.Double" => "double", "System.Boolean" => "bool", "System.String" => "string", "System.Object" => "object",
        "System.Byte" => "byte", "System.Char" => "char", "System.Decimal" => "decimal", "System.Int16" => "short",
        "System.UInt32" => "uint", "System.UInt64" => "ulong",
        _ => null,
    };
    if (alias != null) return alias;
    var name = t.Name;
    if (t.IsGenericType)
    {
        name = name[..name.IndexOf('`')] + "<" + string.Join(", ", t.GetGenericArguments().Select(TypeName)) + ">";
    }
    return t.IsNested && !t.IsGenericParameter ? TypeName(t.DeclaringType!) + "." + name : name;
}

static string DocTypeName(Type t)
{
    var n = t.FullName ?? t.Name;
    return n.Replace('+', '.');
}

static string DocParams(MethodBase m)
{
    var ps = m.GetParameters();
    if (ps.Length == 0) return "";
    return "(" + string.Join(",", ps.Select(p => DocParamType(p.ParameterType, m))) + ")";
}

static string DocParamType(Type t, MethodBase m)
{
    if (t.IsByRef) return DocParamType(t.GetElementType()!, m) + "@";
    if (t.IsArray) return DocParamType(t.GetElementType()!, m) + "[]";
    if (t.IsGenericParameter)
        return t.DeclaringMethod != null ? "``" + t.GenericParameterPosition : "`" + t.GenericParameterPosition;
    if (t.IsGenericType)
    {
        var def = t.GetGenericTypeDefinition().FullName!;
        def = def[..def.IndexOf('`')].Replace('+', '.');
        return def + "{" + string.Join(",", t.GetGenericArguments().Select(a => DocParamType(a, m))) + "}";
    }
    return (t.FullName ?? t.Name).Replace('+', '.');
}
