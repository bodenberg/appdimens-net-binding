import sys, os
# Regenerates DimenFunction + WPF/WinUI/WinForms helper files. Usage: python3 scripts/generate-desktop-api.py
root = sys.argv[1] if len(sys.argv) > 1 else os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
live = [("Sdp","smallest-width scaled dp (layout)"),("Sdpa","Sdp with aspect-ratio curve"),("Hdp","height-axis dp"),("Wdp","width-axis dp"),
        ("Ssp","smallest-width scaled sp (text)"),("Hsp","height-axis sp"),("Wsp","width-axis sp"),("Sspa","Ssp with aspect-ratio curve"),
        ("Hspa","Hsp with aspect-ratio curve"),("Wspa","Wsp with aspect-ratio curve"),("Sem","smallest-width sp without font scale"),
        ("Sema","Sem with aspect-ratio curve"),("Hem","height-axis sp without font scale"),("Hema","Hem with aspect-ratio curve"),
        ("Wem","width-axis sp without font scale"),("Wema","Wem with aspect-ratio curve")]
indep = [("Sdpi","Sdp frozen at startup (does not follow resize)"),("Sdpia","Sdpa frozen at startup"),("Hdpi","Hdp frozen at startup"),
         ("Hdpia","Hdp + aspect ratio, frozen at startup"),("Wdpi","Wdp frozen at startup"),("Wdpia","Wdp + aspect ratio, frozen at startup"),
         ("Sspi","Ssp frozen at startup"),("Sspia","Sspa frozen at startup"),("Hspi","Hsp frozen at startup"),("Wspi","Wsp frozen at startup"),
         ("Semi","Sem frozen at startup"),("Semia","Sema frozen at startup"),("Hemi","Hem frozen at startup"),("Wemi","Wem frozen at startup")]
allf = live + indep
H = "// Generated by scripts/generate-desktop-api.py from the AppDimensResolver API list — edit the script, not this file.\n"

# 1) DimenFunction enum + evaluator (AppDimens.Maui, MAUI-free)
s = H + """namespace AppDimens.Maui;

/// <summary>
/// Every AppDimens SDP/SSP function as a value. Used by the WPF, Windows Forms and WinUI 3
/// adapters (markup extensions, converters, pixel helpers) and handy for data-driven UIs.
/// </summary>
public enum DimenFunction
{
"""
for n,d in allf: s += f"    /// <summary>{d}.</summary>\n    {n},\n"
s += """}

/// <summary>Evaluates a <see cref="DimenFunction"/> through <see cref="AppDimensResolver"/>.</summary>
public static class DimenFunctionExtensions
{
    /// <summary>Returns the scaled value in dp (device-independent units).</summary>
    public static double Evaluate(this DimenFunction function, int value, AppDimensResolver? resolver = null)
    {
        var r = resolver ?? AppDimensResolver.Instance;
        return function switch
        {
"""
for n,_ in allf: s += f"            DimenFunction.{n} => r.{n}(value),\n"
s += """            _ => throw new ArgumentOutOfRangeException(nameof(function), function, null),
        };
    }

    /// <summary>True for the <c>*i</c> (independent) functions that ignore window resizes.</summary>
    public static bool IsIndependent(this DimenFunction function) => function >= DimenFunction.Sdpi;
}
"""
open(os.path.join(root,"appdimens-sdps-net/src/AppDimens.Maui/DimenFunction.cs"),"w").write(s)

def ext_file(ns, using, attr_lines):
    s = H + using + f"\nnamespace {ns};\n"
    for n,d in allf:
        s += f"""
/// <summary><c>{{sdps:{n} 16}}</c> — {d}.</summary>
{attr_lines}public sealed class {n}Extension : DimenExtensionBase
{{
    public {n}Extension() {{ }}
    public {n}Extension(int value) {{ Value = value; }}
    protected override DimenFunction Function => DimenFunction.{n};
}}
"""
    return s
open(os.path.join(root,"appdimens-sdps-net/src/AppDimens.Sdps.Wpf/DimenExtensions.g.cs"),"w").write(
    ext_file("AppDimens.Sdps.Wpf","using System.Windows.Markup;\nusing AppDimens.Maui;\n","[MarkupExtensionReturnType(typeof(object))]\n"))
# WinUI markup extensions cannot take constructor arguments: Value property only.
s = H + "using AppDimens.Maui;\n\nnamespace AppDimens.Sdps.WinUI;\n"
for n,d in allf:
    s += f"""
/// <summary><c>{{sdps:{n} Value=16}}</c> — {d}.</summary>
public sealed class {n}Extension : DimenExtensionBase
{{
    protected override DimenFunction Function => DimenFunction.{n};
}}
"""
open(os.path.join(root,"appdimens-sdps-net/src/AppDimens.Sdps.WinUI/DimenExtensions.g.cs"),"w").write(s)
print("ok")

def int_ext(ns, extra):
    s = H + f"using AppDimens.Maui;\n\nnamespace {ns};\n\n"
    s += "/// <summary>Fluent helpers: <c>16.Sdp()</c> returns device-independent units (dp / DIP).</summary>\npublic static class DimenIntExtensions\n{\n"
    for n,d in allf:
        s += f"    /// <summary>{d} (dp/DIP).</summary>\n    public static double {n}(this int value) => DimenFunction.{n}.Evaluate(value);\n"
        if extra:
            s += f"    /// <summary>{d}, converted to physical pixels for the tracked form.</summary>\n    public static int {n}Px(this int value) => DimenPx.ToPx(DimenFunction.{n}.Evaluate(value));\n"
            s += f"    /// <summary>{d}, converted to font points (for <c>new Font(family, size)</c>).</summary>\n    public static float {n}Pt(this int value) => DimenPx.ToPt(DimenFunction.{n}.Evaluate(value));\n"
    s += "}\n"
    return s
for proj, ns, extra in [("AppDimens.Sdps.Wpf","AppDimens.Sdps.Wpf",False),("AppDimens.Sdps.WinUI","AppDimens.Sdps.WinUI",False),("AppDimens.Sdps.WinForms","AppDimens.Sdps.WinForms",True)]:
    open(os.path.join(root,f"appdimens-sdps-net/src/{proj}/DimenIntExtensions.g.cs"),"w").write(int_ext(ns, extra))
print("ok2")
